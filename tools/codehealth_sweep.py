#!/usr/bin/env python3
"""Sweep every tracked C# file in Jellyfin through CodeScene Code Health.

Reviews each file through the CodeScene MCP server (`code_health_review`), so that
every measurement is recorded on the CodeScene side, and records each file's score and
the code smells behind it (category, function, lines), tagged with a category so the
band distribution can be reported with or without tests and generated code.

The server is started from the "codescene" entry of the repository's .mcp.json and kept
open for the whole sweep (cs_mcp_client.py). An earlier note here said the server drops an
answer still in flight 5 seconds after its input closes, so large files such as
EncodingHelper.cs came back silent; that is true for a one-shot call that closes the input
at once. A client that keeps the input open gets the same answers as the CLI. When the
server cannot be reached, or gives no review for a file, the sweep falls back to the CodeScene
CLI for that file (`cs review --output-format=json`): the one bundled with the MCP server
(%LOCALAPPDATA%/codehealth-mcp/MCP-<version>/cs.exe); set CS_CLI to override. The CLI says
which is which: {"score": null} means no functions; no JSON at all means the run failed.
Use --backend cli or --backend mcp to force one of them.

Started from the 3SX campaign's tools/codehealth_sweep.py.
Requires CS_ACCESS_TOKEN in the environment.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from cs_mcp_client import McpClient, McpUnavailable, parse_review  # noqa: E402

BACKEND = "auto"  # auto: the MCP server, then the CLI; mcp: the server only; cli: the CLI only
_mcp: McpClient | None = None  # one server process, one file at a time (see mcp_data)
_mcp_lock = threading.Lock()
_mcp_down = False
BANDS = ("red", "yellow", "green", "optimal")
CATEGORIES = ("production", "test", "generated", "fuzz")


def category(path: str) -> str:
    """Which group a file belongs to. Only 'production' is campaign scope by default."""
    if path.startswith("tests/"):
        return "test"
    if path.startswith("fuzz/"):
        return "fuzz"
    # EF Core migrations, their designer files and model snapshots are generated by
    # `dotnet ef`. Jellyfin.Server/Migrations is hand-written and stays production.
    if path.startswith("src/Jellyfin.Database/") and "/Migrations/" in path:
        return "generated"
    return "production"


def band(score: float) -> str:
    if score >= 10.0:
        return "optimal"
    if score >= 9.0:
        return "green"
    if score >= 4.0:
        return "yellow"
    return "red"


def find_cli() -> str:
    override = os.environ.get("CS_CLI")
    if override:
        if not Path(override).is_file():
            sys.exit("CS_CLI is set but does not exist: " + override)
        return override
    root = Path(os.environ.get("LOCALAPPDATA", "")) / "codehealth-mcp"
    if root.is_dir():
        for version_dir in sorted(root.iterdir(), reverse=True):
            for name in ("cs.exe", "cs"):
                exe = version_dir / name
                if exe.is_file():
                    return str(exe)
    sys.exit("Could not find the CodeScene CLI; run the CodeScene MCP server once, or set CS_CLI.")


def cli_version(exe: str) -> str:
    out = subprocess.run([exe, "version"], capture_output=True, text=True, cwd=REPO).stdout
    for line in out.splitlines():
        if line.startswith("cs version"):
            return line.split()[2]
    return "unknown"


def candidates() -> list[str]:
    out = subprocess.run(["git", "ls-files", "*.cs"], cwd=REPO, capture_output=True, text=True).stdout
    return sorted(line.strip() for line in out.splitlines() if line.strip())


def mcp_data(rel: str) -> dict | None:
    """The review of one file from the MCP server, or None when it cannot give one."""
    global _mcp, _mcp_down
    if BACKEND == "cli" or _mcp_down:
        return None
    with _mcp_lock:
        if _mcp_down:
            return None
        try:
            if _mcp is None:
                _mcp = McpClient.from_repo(REPO)
            text = _mcp.call("code_health_review", {"file_path": str(REPO / rel)})
        except McpUnavailable as exc:
            _mcp_down = True
            print("note: the CodeScene MCP server is unavailable (%s); the rest uses the CLI" % exc,
                  file=sys.stderr)
            return None
    return parse_review(text)


def review(exe: str | None, rel: str) -> dict:
    """One file. Returns {'score': float|None, 'smells': [...]} or {'error': text}."""
    data = mcp_data(rel)
    if data is None and BACKEND == "mcp":
        return {"error": "the MCP server gave no review"}
    if data is None:
        exe = exe or find_cli()
        env = dict(os.environ, CS_DISABLE_VERSION_CHECK="1")
        proc = subprocess.run([exe, "review", "--output-format=json", rel], cwd=REPO, env=env,
                              capture_output=True, text=True, encoding="utf-8", errors="replace")
        try:
            data = json.loads(proc.stdout)
        except json.JSONDecodeError:
            lines = [ln for ln in (proc.stderr or "").splitlines() if "version" not in ln.lower()]
            return {"error": " ".join(" ".join(lines).split())[:200] or "no output"}
    smells = []
    for item in data.get("review", []):
        smells.append({
            "category": item.get("category"),
            "indication": item.get("indication"),
            "functions": [
                {k: f[k] for k in ("title", "details", "start-line", "end-line") if k in f}
                for f in item.get("functions", [])
            ],
        })
    return {"score": data.get("score"), "smells": smells}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("-o", "--output",
                    default=str(REPO / "docs" / "refactoring" / "codehealth-baseline.json"))
    ap.add_argument("--jobs", type=int, default=8, help="CLI processes in parallel (the MCP server is used one file at a time: parallel server "
                         "processes trip its rate limit)")
    ap.add_argument("--backend", choices=("auto", "mcp", "cli"), default="auto",
                    help="auto (default): the MCP server, then the CLI; mcp: the server only; cli: the CLI only")
    ap.add_argument("--limit", type=int, default=0, help="review only the first N files")
    ap.add_argument("files", nargs="*", help="review these files only (default: every tracked .cs)")
    args = ap.parse_args()

    if not os.environ.get("CS_ACCESS_TOKEN"):
        print("warning: CS_ACCESS_TOKEN is not set", file=sys.stderr)

    global BACKEND
    BACKEND = args.backend
    exe = find_cli() if BACKEND != "mcp" else None
    files = args.files or candidates()
    if args.limit:
        files = files[:args.limit]
    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=REPO, capture_output=True,
                            text=True).stdout.strip()
    dirty = bool(subprocess.run(["git", "status", "--porcelain", "--untracked-files=no"], cwd=REPO,
                                capture_output=True, text=True).stdout.strip())
    version = cli_version(exe) if exe else "unknown"
    print("cs %s: %s" % (version, exe or "MCP server"))
    print("reviewing %d files via %s" % (len(files), {"auto": "the MCP server (CLI as fallback)",
                                                      "mcp": "the MCP server", "cli": "the CLI"}[BACKEND]))

    started = time.time()
    results = {}
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        for n, (rel, res) in enumerate(zip(files, pool.map(lambda f: review(exe, f), files)), 1):
            results[rel] = res
            if n % 50 == 0 or n == len(files):
                print("  %d/%d" % (n, len(files)), end="\r", flush=True)
    print()

    failed = [(rel, r["error"]) for rel, r in results.items() if "error" in r]
    if failed:
        for rel, text in failed[:10]:
            print("  " + rel + ": " + text, file=sys.stderr)
        sys.exit("%d files failed; nothing written" % len(failed))

    rows, unscorable = [], []
    for rel, r in results.items():
        if r["score"] is None:
            unscorable.append(rel)
            continue
        rows.append({"path": rel, "score": round(r["score"], 2), "raw_score": r["score"],
                     "category": category(rel), "band": band(r["score"]), "smells": r["smells"]})
    rows.sort(key=lambda row: (row["raw_score"], row["path"]))

    summary = {}
    for cat in CATEGORIES:
        vals = [row["raw_score"] for row in rows if row["category"] == cat]
        summary[cat] = {
            "scored": len(vals),
            "unscorable": sum(1 for p in unscorable if category(p) == cat),
            "bands": {b: sum(1 for row in rows if row["category"] == cat and row["band"] == b)
                      for b in BANDS},
            "mean": round(sum(vals) / len(vals), 3) if vals else None,
        }

    payload = {
        "commit": commit,
        "dirty": dirty,
        "cs_version": version,
        "measured": time.strftime("%Y-%m-%d"),
        "seconds": round(time.time() - started),
        "total_candidates": len(files),
        "scored": len(rows),
        "unscorable": len(unscorable),
        "summary": summary,
        "files": rows,
        "unscorable_files": sorted(unscorable),
    }
    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    Path(args.output).write_text(json.dumps(payload, indent=1) + "\n", encoding="utf-8")

    print("scored %d of %d files in %ds (%d have no functions)"
          % (len(rows), len(files), payload["seconds"], len(unscorable)))
    print("%-11s %6s %5s %6s %6s %7s %6s" % ("", "scored", "red", "yellow", "green", "optimal", "mean"))
    for cat, s in summary.items():
        b = s["bands"]
        print("%-11s %6d %5d %6d %6d %7d %6s" % (cat, s["scored"], b["red"], b["yellow"], b["green"],
                                                b["optimal"], s["mean"]))
    print("wrote " + args.output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
